    private void stilizujFormu() {
        getContentPane().setBackground(new Color(245, 248, 252));
        labelStatus.setFont(new Font("Segoe UI", Font.BOLD, 17));
        labelStatus.setForeground(new Color(25, 90, 160));
        jMenu1.setFont(new Font("Segoe UI", Font.BOLD, 16));
        jMenu1.setForeground(new Color(25, 90, 160));
        jTextFieldStatus.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        jTextFieldStatus.setBackground(new Color(230, 240, 255));
        jTextFieldStatus.setForeground(new Color(25, 90, 160));
        jTextFieldStatus.setBorder(BorderFactory.createLineBorder(
                new Color(100, 160, 220), 1));
        stilizujDugme(btnPokreni);
        stilizujDugme(btnZaustavi);

        btnPokreni.setFont(new Font("Segoe UI", Font.BOLD, 14));
        btnZaustavi.setFont(new Font("Segoe UI", Font.BOLD, 13));
        btnZaustavi.setBackground(new Color(180, 40, 40));
        btnZaustavi.setForeground(Color.WHITE);
        btnZaustavi.setOpaque(true);
        btnZaustavi.setBorderPainted(false);

        btnPokreni.setBackground(new Color(34, 139, 34));
        btnPokreni.addMouseListener(new java.awt.event.MouseAdapter() {
            public void mouseEntered(java.awt.event.MouseEvent e) {
                btnPokreni.setBackground(new Color(20, 100, 20));
            }

            public void mouseExited(java.awt.event.MouseEvent e) {
                btnPokreni.setBackground(new Color(34, 139, 34));
            }
        });

        btnZaustavi.setBackground(new Color(180, 40, 40));
        btnZaustavi.addMouseListener(new java.awt.event.MouseAdapter() {
            public void mouseEntered(java.awt.event.MouseEvent e) {
                btnZaustavi.setBackground(new Color(140, 20, 20));
            }

            public void mouseExited(java.awt.event.MouseEvent e) {
                btnZaustavi.setBackground(new Color(180, 40, 40));
            }
        });
    } // ← kraj stilizujFormu()

// ← OVDJE dodaj novu metodu, još uvijek unutar klase
    private void stilizujDugme(JButton btn) {
        btn.setFont(new Font("Segoe UI", Font.BOLD, 13));
        btn.setForeground(Color.WHITE);
        btn.setFocusPainted(false);
        btn.setBorderPainted(false);
        btn.setOpaque(true);
        btn.setCursor(new Cursor(Cursor.HAND_CURSOR));
    }

