    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
        int port;
        try {
            port = Integer.parseInt(jTextFieldPort.getText());
        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, "Port mora biti broj!", "GRESKA!", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (port >= 0 && port <= 65535) {//ovo je max broj za port
            Konfiguracija.getInstance().setProperty("port", port + "");
            Konfiguracija.getInstance().sacuvajIzmene();
            JOptionPane.showMessageDialog(this, "Parametar je sacuvan!", "USPEH!", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Port nije u dobrom opsegu!", "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

