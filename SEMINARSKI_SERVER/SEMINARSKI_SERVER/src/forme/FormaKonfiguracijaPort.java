    private void stilizujFormu() {
        getContentPane().setBackground(new Color(245, 248, 252));

        labelNaslov.setText("<html><b>Unesite port servera:</b></html>");
        labelNaslov.setFont(new Font("Segoe UI", Font.BOLD, 15));
        labelNaslov.setForeground(new Color(25, 90, 160));

        labelPort.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        labelPort.setForeground(new Color(60, 60, 80));

        stilizujTextField(jTextFieldPort);
        stilizujDugme(btnSacuvaj);

    }

    private void stilizujTextField(JTextField field) {
        field.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        field.setBackground(Color.WHITE);
        field.setForeground(new Color(30, 30, 50));
        field.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(new Color(100, 160, 220), 1),
                BorderFactory.createEmptyBorder(4, 8, 4, 8)
        ));
    }

    private void stilizujDugme(JButton btn) {
        btn.setFont(new Font("Segoe UI", Font.BOLD, 13));
        btn.setBackground(new Color(25, 90, 160));
        btn.setForeground(Color.WHITE);
        btn.setFocusPainted(false);
        btn.setBorderPainted(false);
        btn.setOpaque(true);
        btn.setCursor(new Cursor(Cursor.HAND_CURSOR));

        // Hover efekat
        btn.addMouseListener(new java.awt.event.MouseAdapter() {
            public void mouseEntered(java.awt.event.MouseEvent e) {
                btn.setBackground(new Color(15, 65, 130));
            }

            public void mouseExited(java.awt.event.MouseEvent e) {
                btn.setBackground(new Color(25, 90, 160));
            }
        });
    }
